// @ts-check
// Insurance report — lays a collection valuation out as a multi-page A4 PDF
// (lib/pdf-writer.js). Pure: the caller passes pre-formatted money strings,
// labels and optional JPEG photo bytes, so this runs the same in the browser
// and in unit tests.
import { PdfDocument, A4, wrapText, winAnsiSupported } from './pdf-writer.js';

/** English labels — also the fallback when a translation can't be drawn with the PDF's standard fonts. */
export const REPORT_LABELS_EN = {
  kicker: 'COLLECTION VALUATION',
  title: '{owner} · {date}',
  counts: '{sets} sets · {figs} minifigures · values in {currency}',
  countsNoFigs: '{sets} sets · values in {currency}',
  totalValue: 'Total market value',
  totalPaid: 'Total paid',
  colSet: 'Set',
  colNumber: 'Number',
  colQty: 'Qty',
  colPaid: 'Paid',
  colValue: 'Value',
  minifigures: 'Minifigures',
  noteTitle: 'About these values',
  note: 'Values are market estimates for sealed sets as of {date}, blended from recent sales and listings across the sources BricksVault tracks. They are not an appraisal. Method: bricksvault.app/methodology.html',
  page: 'Page {page} of {pages}',
  generated: 'Generated by BricksVault',
};

/** @param {string} tpl @param {Record<string, unknown>} vars */
function fill(tpl, vars) {
  return String(tpl).replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
}

/**
 * Use the translated labels only if every one of them can be drawn;
 * otherwise the whole report stays in English (no half-translated pages).
 * @param {Partial<typeof REPORT_LABELS_EN>} [labels]
 */
export function reportLabels(labels) {
  if (!labels) return { ...REPORT_LABELS_EN };
  const merged = { ...REPORT_LABELS_EN, ...labels };
  return Object.values(merged).every((v) => winAnsiSupported(v)) ? merged : { ...REPORT_LABELS_EN };
}

/**
 * @typedef {{ name: string, number: string, meta?: string, qty?: number, value: string, paid?: string, photo?: Uint8Array | null }} ReportItem
 * @typedef {{
 *   owner: string, date: string, currency: string,
 *   totals: { value: string, paid?: string, sets: number, figs: number },
 *   items: ReportItem[], figs?: ReportItem[],
 *   options?: { photos?: boolean, paid?: boolean, figs?: boolean },
 *   labels?: Partial<typeof REPORT_LABELS_EN>,
 * }} ReportInput
 */

const M = 48;               // page margin
const INK = '#252820';
const MUTE = '#5b5f53';
const LINE = '#dadcd1';
const ACCENT = '#6b5000';

/**
 * Build the report. Returns the PDF bytes and the page count.
 * @param {ReportInput} input
 */
export function buildInsuranceReport(input) {
  const L = reportLabels(input.labels);
  const opts = { photos: true, paid: false, figs: true, ...(input.options || {}) };
  const doc = new PdfDocument({ title: `${L.kicker} — ${input.owner}`, author: input.owner });
  const W = A4.width;
  const H = A4.height;
  const right = W - M;
  const footerTop = H - M - 26;
  const rowH = opts.photos ? 44 : 24;
  const colValue = right;
  const colPaid = right - 92;
  const colQty = opts.paid ? right - 170 : right - 92;
  const nameX = M + (opts.photos ? 46 : 0);
  const nameMax = colQty - 40 - nameX;

  /** @type {import('./pdf-writer.js').PdfPage[]} */
  const pages = [];
  let page = doc.addPage();
  pages.push(page);
  let y = M;

  // ---- Header (first page).
  page.text(M, y + 10, L.kicker, { size: 9, bold: true, color: ACCENT });
  y += 32;
  page.text(M, y, fill(L.title, { owner: input.owner, date: input.date }), { size: 20, bold: true, maxWidth: right - M });
  y += 18;
  const counts = opts.figs && input.totals.figs > 0 ? L.counts : L.countsNoFigs;
  page.text(M, y, fill(counts, { sets: input.totals.sets, figs: input.totals.figs, currency: input.currency }), { size: 10, color: MUTE, maxWidth: right - M });
  y += 16;
  page.rect(M, y, right - M, opts.paid && input.totals.paid ? 62 : 42, { fill: '#f7f5ee', stroke: LINE, lineWidth: 0.75 });
  page.text(M + 14, y + 26, L.totalValue, { size: 11 });
  page.text(right - 14, y + 27, input.totals.value, { size: 18, bold: true, align: 'right' });
  if (opts.paid && input.totals.paid) {
    page.text(M + 14, y + 48, L.totalPaid, { size: 10, color: MUTE });
    page.text(right - 14, y + 48, input.totals.paid, { size: 11, bold: true, align: 'right', color: MUTE });
    y += 62;
  } else y += 42;
  y += 22;

  const header = (title) => {
    page.text(M, y, title, { size: 9, bold: true, color: MUTE });
    page.text(colQty, y, L.colQty, { size: 9, bold: true, color: MUTE, align: 'right' });
    if (opts.paid) page.text(colPaid, y, L.colPaid, { size: 9, bold: true, color: MUTE, align: 'right' });
    page.text(colValue, y, L.colValue, { size: 9, bold: true, color: MUTE, align: 'right' });
    y += 8;
    page.line(M, y, right, y, { color: INK, lineWidth: 0.75 });
  };
  const newPage = (title) => {
    page = doc.addPage();
    pages.push(page);
    y = M + 10;
    header(title);
  };
  /** @param {ReportItem} it @param {string} title */
  const itemRow = (it, title) => {
    if (y + rowH > footerTop) newPage(title);
    const top = y;
    if (opts.photos) {
      const img = it.photo ? doc.addJpeg(it.photo) : null;
      if (img) {
        const info = doc.jpegs.get(img);
        const scale = Math.min(36 / (info?.width || 36), 36 / (info?.height || 36));
        const w = (info?.width || 36) * scale;
        const h = (info?.height || 36) * scale;
        page.image(img, M + (36 - w) / 2, top + 4 + (36 - h) / 2, w, h);
      } else {
        page.rect(M, top + 4, 36, 36, { fill: '#efede4' });
      }
    }
    const base = opts.photos ? top + 20 : top + 16;
    page.text(nameX, base, it.name, { size: 10.5, bold: true, maxWidth: nameMax });
    const sub = [it.number, it.meta].filter(Boolean).join(' · ');
    if (sub) page.text(nameX, base + 13, sub, { size: 8.5, color: MUTE, maxWidth: nameMax });
    page.text(colQty, base, String(it.qty || 1), { size: 10 , align: 'right' });
    if (opts.paid) page.text(colPaid, base, it.paid || '—', { size: 10, align: 'right', color: MUTE });
    page.text(colValue, base, it.value, { size: 10.5, bold: true, align: 'right' });
    y += rowH + (opts.photos ? 0 : 6);
    page.line(M, y, right, y);
  };

  header(L.colSet);
  for (const it of input.items) itemRow(it, L.colSet);

  const figs = opts.figs ? input.figs || [] : [];
  if (figs.length) {
    if (y + 40 + rowH > footerTop) newPage(L.minifigures);
    else { y += 22; header(L.minifigures); }
    for (const it of figs) itemRow(it, L.minifigures);
  }

  // Methodology note after the table.
  const noteLines = wrapText(fill(L.note, { date: input.date }), 9, right - M);
  if (y + 30 + noteLines.length * 12 > footerTop) { page = doc.addPage(); pages.push(page); y = M; }
  y += 26;
  page.text(M, y, L.noteTitle, { size: 9, bold: true, color: MUTE });
  for (const line of noteLines) { y += 12; page.text(M, y, line, { size: 9, color: MUTE }); }

  // Footers once the page count is known.
  pages.forEach((p, i) => {
    p.line(M, H - M - 14, right, H - M - 14);
    p.text(M, H - M, L.generated, { size: 8, color: MUTE });
    p.text(right, H - M, fill(L.page, { page: i + 1, pages: pages.length }), { size: 8, color: MUTE, align: 'right' });
  });
  return { bytes: doc.toBytes(), pages: pages.length };
}
